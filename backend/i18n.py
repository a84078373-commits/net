def normalize_lang(code) -> str | None:
    if not isinstance(code, str):
        return None
    code = code.strip().lower()[:2]
    return code if code in LANGS else None


def translate(text: str, lang: str, **params) -> str:
    out = EN.get(text, text) if lang == 'en' else text
    if params:
        out = out.format(
            **{k: translate(v, lang) if isinstance(v, str) else v for k, v in params.items()}
        )
    return out


